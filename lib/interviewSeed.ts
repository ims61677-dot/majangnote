// 면접지 양식 구조 + 기본 홀 양식
export type TplItem = {
  id: string
  type: 'text' | 'long' | 'question' | 'checks' | 'yesno' | 'note'
  label?: string      // 항목 제목
  text?: string       // 질문 문구 / 안내문 (여러 줄 가능)
  guide?: string      // 평가 가이드 (여러 줄, ✅ ⚠️ ❌ ➖ 등)
  options?: string    // 체크박스 항목 (한 줄에 하나)
}
export type TplSection = { id: string; title: string; note?: string; items: TplItem[] }
export type Tpl = { sections: TplSection[] }

let _n = 0
export const newId = () => `i${Date.now().toString(36)}${(_n++).toString(36)}${Math.random().toString(36).slice(2, 5)}`

const T = (label: string, text?: string): TplItem => ({ id: newId(), type: 'text', label, text })
const L = (label: string, text?: string): TplItem => ({ id: newId(), type: 'long', label, text })
const Q = (label: string, text: string, guide?: string): TplItem => ({ id: newId(), type: 'question', label, text, guide })
const C = (label: string, options: string[]): TplItem => ({ id: newId(), type: 'checks', label, options: options.join('\n') })
const Y = (label: string, text?: string): TplItem => ({ id: newId(), type: 'yesno', label, text })
const N = (text: string): TplItem => ({ id: newId(), type: 'note', text })
const S = (title: string, items: TplItem[], note?: string): TplSection => ({ id: newId(), title, note, items })

